"""Render findings as a Markdown block an agent reads, and keep it updated in a file."""
from __future__ import annotations

import os
import re

from .analyze import Report

START = "<!-- postcutoff:start -->"
END = "<!-- postcutoff:end -->"

WHY = {
    "new-package": "the package did not exist yet",
    "major": "new major version",
    "minor": "new minor version",
    "patch": "patch releases only",
}


def link(ecosystem: str, name: str, version: str) -> str:
    if ecosystem == "pypi":
        return "https://pypi.org/project/%s/%s/" % (name, version)
    return "https://www.npmjs.com/package/%s/v/%s" % (name, version)


def render_markdown(report: Report) -> str:
    rows = [f for f in report.findings if f.level in WHY]
    lines = [START, "## Dependencies newer than your training data", ""]
    if not rows:
        lines.append(
            "Every pinned dependency in this project was released on or before %s. "
            "(Generated by postcutoff.)" % report.cutoff.isoformat())
    else:
        lines.append(
            "These pinned versions were released after %s, so you have not seen them. "
            "Do not write code against them from memory: read the changelog or docs "
            "linked below first, and prefer what the installed package actually exposes. "
            "(Generated by postcutoff.)" % report.cutoff.isoformat())
        lines.append("")
        for f in rows:
            name = "`%s`" % f.dep.name + (" (npm)" if f.dep.ecosystem == "npm" else "")
            what = "%s %s (%s, released %s)" % (
                name, f.dep.version, WHY[f.level], f.released.isoformat() if f.released else "?")
            if f.known:
                what += "; the newest version you may know is %s" % f.known
            lines.append("- %s: %s" % (what, link(f.dep.ecosystem, f.dep.name, f.dep.version)))
    lines.append(END)
    return "\n".join(lines) + "\n"


_BLOCK = re.compile(re.escape(START) + r".*?" + re.escape(END) + r"\n?", re.S)


def write_block(path: str, block: str) -> str:
    """Insert or replace the postcutoff block in `path`. Returns created/updated/unchanged."""
    if not os.path.exists(path):
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(block)
        return "created"
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    if _BLOCK.search(text):
        new = _BLOCK.sub(lambda _m: block, text, count=1)
    else:
        if not text or text.endswith("\n\n"):
            sep = ""
        elif text.endswith("\n"):
            sep = "\n"
        else:
            sep = "\n\n"
        new = text + sep + block
    if new == text:
        return "unchanged"
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(new)
    return "updated"
